// Truly seamless ticker: keep enough copies for ultrawide screens and animate exactly one group width.
const tickerTrack = document.querySelector('[data-ticker-track]');
const tickerGroup = document.querySelector('[data-ticker-group]');
const refreshTicker = () => {
  if (!tickerTrack || !tickerGroup) return;
  tickerTrack.querySelectorAll('.ticker-group[data-clone="true"]').forEach((node) => node.remove());
  const groupWidth = tickerGroup.getBoundingClientRect().width;
  if (!groupWidth) return;
  const gap = 32;
  const copies = Math.max(2, Math.ceil((window.innerWidth * 2.4) / (groupWidth + gap)) + 1);
  for (let i = 1; i < copies; i += 1) {
    const clone = tickerGroup.cloneNode(true);
    clone.dataset.clone = 'true';
    clone.setAttribute('aria-hidden', 'true');
    tickerTrack.appendChild(clone);
  }
  tickerTrack.style.setProperty('--ticker-distance', `${-(groupWidth + gap)}px`);
};
window.refreshHellionzTicker = refreshTicker;
refreshTicker();
let tickerResizeTimer;
window.addEventListener('resize', () => {
  clearTimeout(tickerResizeTimer);
  tickerResizeTimer = setTimeout(refreshTicker, 120);
}, { passive: true });

// Screenshot carousel.
const carousel = document.querySelector('[data-carousel]');
const track = document.querySelector('[data-carousel-track]');
const slides = [...document.querySelectorAll('.screenshot-slide')];
const dotsRoot = document.querySelector('[data-carousel-dots]');
const prevButton = document.querySelector('[data-carousel-prev]');
const nextButton = document.querySelector('[data-carousel-next]');
let currentSlide = 0;
let carouselTimer = null;

const showSlide = (index) => {
  if (!slides.length || !track) return;
  currentSlide = (index + slides.length) % slides.length;
  track.style.transform = `translate3d(-${currentSlide * 100}%,0,0)`;
  slides.forEach((slide, i) => slide.classList.toggle('is-active', i === currentSlide));
  if (dotsRoot) [...dotsRoot.children].forEach((dot, i) => dot.classList.toggle('is-active', i === currentSlide));
};

if (dotsRoot && slides.length) {
  dotsRoot.innerHTML = '';
  slides.forEach((_, index) => {
    const dot = document.createElement('button');
    dot.type = 'button';
    dot.setAttribute('aria-label', `Screenshot ${index + 1}`);
    dot.addEventListener('click', () => {
      showSlide(index);
      restartCarousel();
    });
    dotsRoot.appendChild(dot);
  });
}
if (prevButton) prevButton.addEventListener('click', () => { showSlide(currentSlide - 1); restartCarousel(); });
if (nextButton) nextButton.addEventListener('click', () => { showSlide(currentSlide + 1); restartCarousel(); });
showSlide(0);

const startCarousel = () => {
  if (reducedMotion || slides.length < 2) return;
  clearInterval(carouselTimer);
  carouselTimer = setInterval(() => showSlide(currentSlide + 1), 4800);
};
const restartCarousel = () => {
  clearInterval(carouselTimer);
  startCarousel();
};
if (carousel) {
  startCarousel();
  carousel.addEventListener('mouseenter', () => clearInterval(carouselTimer));
  carousel.addEventListener('mouseleave', startCarousel);
  let touchStartX = 0;
  carousel.addEventListener('touchstart', (event) => { touchStartX = event.changedTouches[0].clientX; }, { passive: true });
  carousel.addEventListener('touchend', (event) => {
    const delta = event.changedTouches[0].clientX - touchStartX;
    if (Math.abs(delta) > 42) {
      showSlide(currentSlide + (delta < 0 ? 1 : -1));
      restartCarousel();
    }
  }, { passive: true });
}

