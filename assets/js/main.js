const supportedLanguages = ['en', 'ru', 'es', 'uk'];
const languageLabels = { en: 'EN', ru: 'RU', es: 'ES', uk: 'UK' };

const applyLanguage = (lang) => {
  const safeLang = supportedLanguages.includes(lang) ? lang : 'en';
  const dict = translations[safeLang];
  document.documentElement.lang = safeLang;
  document.querySelectorAll('[data-i18n]').forEach((node) => {
    const key = node.dataset.i18n;
    if (dict[key] !== undefined) node.textContent = dict[key];
  });
  document.querySelectorAll('[data-i18n-html]').forEach((node) => {
    const key = node.dataset.i18nHtml;
    if (dict[key] !== undefined) node.innerHTML = dict[key];
  });
  document.title = dict.metaTitle;
  const description = document.querySelector('meta[name="description"]');
  const ogTitle = document.querySelector('meta[property="og:title"]');
  const ogDescription = document.querySelector('meta[property="og:description"]');
  if (description) description.content = dict.metaDescription;
  if (ogTitle) ogTitle.content = dict.metaTitle;
  if (ogDescription) ogDescription.content = dict.metaDescription;
  const currentLabel = document.querySelector('[data-language-current-label]');
  if (currentLabel) currentLabel.textContent = languageLabels[safeLang];
  document.querySelectorAll('[data-lang]').forEach((button) => button.setAttribute('aria-selected', String(button.dataset.lang === safeLang)));
  localStorage.setItem('hellionz-language', safeLang);
  window.requestAnimationFrame(() => window.refreshHellionzTicker?.());
};

const savedLanguage = localStorage.getItem('hellionz-language');
const browserLanguage = (navigator.language || 'en').slice(0, 2).toLowerCase();
applyLanguage(savedLanguage || (supportedLanguages.includes(browserLanguage) ? browserLanguage : 'en'));

